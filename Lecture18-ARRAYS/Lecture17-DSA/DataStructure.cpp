// What is Data Structures?

// In life, we store data in different ways for different porposes!

// A data structure is a specialized way of organizing and storing 
// data in a computer so it can be accessed, modified, and managed 
// efficiently. It defines both the logical representation of data
//  and its physical implementation in memory, making it fundamental 
//  to programming and algorithm design.



// 🔑 Key Points About Data Structures
// Definition: A data structure is a format for organizing data so that it can be used effectively by computer programs.

// Purpose: Enables efficient operations such as searching, sorting, insertion, deletion, and traversal.

// Relation to Algorithms: Data structures are tightly linked to algorithms; the choice of structure often determines the efficiency of an algorithm.

// 📂 Types of Data Structures
// 1. Linear Data Structures
// Elements arranged sequentially.

// Examples:

// Array: Fixed-size, indexed collection.

// Stack: Follows LIFO (Last In, First Out).

// Queue: Follows FIFO (First In, First Out).

// 2. Non-Linear Data Structures
// Elements connected in hierarchical or networked ways.

// Examples:

// Tree: Hierarchical structure with nodes and edges.

// Graph: Network of nodes connected by edges.

// 📊 Comparison Table
// Type	Structure Style	Examples	Best Use Case
// Array	Linear, fixed	[1,2,3,4]	Fast indexed access
// Stack	Linear, LIFO	Browser history	Undo operations
// Queue	Linear, FIFO	Print queue	Task scheduling
// Tree	Hierarchical	Binary tree	File systems
// Graph	Networked	Social network	Pathfinding, relationships


// ⚙️ Applications of Data Structures
// Databases: B-trees for indexing.

// Operating Systems: Linked lists for memory management.

// Computer Graphics: Trees and arrays for rendering.

// AI & Machine Learning: Graphs for knowledge representation.